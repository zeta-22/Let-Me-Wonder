// Packs src/filter/ into one script, saved twice:
//   dist/let-me-wonder.user.js            for Safari on iPhone (Userscripts app)
//   src/filter/generated/filterBundle.js  for the Android app, which injects it
// Usage: npm run build:filter

import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const pkg = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const repo = 'zeta-22/Let-Me-Wonder';
const scriptUrl = `https://raw.githubusercontent.com/${repo}/main/dist/let-me-wonder.user.js`;

const result = await build({
  entryPoints: [new URL('src/filter/filter.js', root).pathname],
  bundle: true,
  format: 'iife',
  target: ['safari15', 'chrome100'],
  loader: { '.css': 'text' },
  define: { __LMW_VERSION__: JSON.stringify(pkg.version) },
  legalComments: 'none',
  write: false,
});
const code = result.outputFiles[0].text;

const header = `// ==UserScript==
// @name         Let Me Wonder
// @namespace    https://github.com/${repo}
// @version      ${pkg.version}
// @description  Instagram without Reels, Explore, suggestions and ads.
// @match        https://www.instagram.com/*
// @match        https://instagram.com/*
// @run-at       document-start
// @inject-into  content
// @noframes
// @grant        none
// @homepageURL  https://github.com/${repo}
// @updateURL    ${scriptUrl}
// @downloadURL  ${scriptUrl}
// ==/UserScript==

// Built from src/filter/ by scripts/build-filter.mjs. Edit those files, not this one.
`;

await mkdir(new URL('dist/', root), { recursive: true });
await writeFile(new URL('dist/let-me-wonder.user.js', root), header + code);

await mkdir(new URL('src/filter/generated/', root), { recursive: true });
await writeFile(
  new URL('src/filter/generated/filterBundle.js', root),
  `// Generated by scripts/build-filter.mjs from src/filter/. Don't edit.\n` +
    `export const FILTER_VERSION = ${JSON.stringify(pkg.version)};\n` +
    `export default ${JSON.stringify(code)};\n`,
);
console.log(`Built the filter (version ${pkg.version}, ${(code.length / 1024).toFixed(1)} KB) for Safari and the app`);
